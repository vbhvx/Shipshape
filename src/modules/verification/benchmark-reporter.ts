import fs from 'fs/promises';
import path from 'path';

export interface BenchmarkReportPayload {
  timestamp: string;
  environment: {
    nodeVersion: string;
    playwrightInstalled: boolean;
    dockerAvailable: boolean;
  };
  metrics: {
    contractEvaluatedCount: number;
    realBrowserTestedCount: number;
    passedCount: number;
    failedCount: number;
    overallPassRate: number;
  };
  results: Array<{
    scenarioId: string;
    mode: 'contract_check' | 'preview_simulation' | 'headless_chromium' | 'docker_execution';
    passed: boolean;
    durationMs: number;
    stepSummary: string;
    errors?: string[];
  }>;
}

/**
 * BenchmarkReporter: Produces empirical reports with strict separation between
 * benchmark contract specifications, preview simulations, and live browser executions.
 */
export class BenchmarkReporter {
  static generateJsonReport(payload: BenchmarkReportPayload): string {
    return JSON.stringify(payload, null, 2);
  }

  static generateMarkdownReport(payload: BenchmarkReportPayload): string {
    const lines: string[] = [
      '# Shipshape — Empirical Benchmark Evaluation Report',
      '',
      `**Generated At:** ${payload.timestamp}  `,
      `**Node Version:** ${payload.environment.nodeVersion}  `,
      `**Playwright Headless Shell:** ${payload.environment.playwrightInstalled ? 'Installed & Verified' : 'Missing'}  `,
      `**Docker Daemon:** ${payload.environment.dockerAvailable ? 'Available' : 'Not Connected (Cleanly Skipped)'}  `,
      '',
      '## Execution Metrics Summary',
      '',
      '| Metric | Value |',
      '|---|---|',
      `| Contract Specifications Validated | ${payload.metrics.contractEvaluatedCount} |`,
      `| Live Browser Applications Verified | ${payload.metrics.realBrowserTestedCount} |`,
      `| Passed | ${payload.metrics.passedCount} |`,
      `| Failed | ${payload.metrics.failedCount} |`,
      `| Success Rate | ${(payload.metrics.overallPassRate * 100).toFixed(1)}% |`,
      '',
      '## Scenario Breakdown',
      '',
      '| Scenario ID | Mode | Status | Duration | Steps | Diagnostics |',
      '|---|---|---|---|---|---|',
    ];

    for (const r of payload.results) {
      const statusIcon = r.passed ? 'PASSED' : 'FAILED';
      const errorNote = r.errors && r.errors.length > 0 ? r.errors.join('; ') : 'None';
      lines.push(
        `| \`${r.scenarioId}\` | \`${r.mode}\` | **${statusIcon}** | ${r.durationMs}ms | ${r.stepSummary} | ${errorNote} |`
      );
    }

    lines.push('');
    lines.push('---');
    lines.push('*Report generated by Shipshape BenchmarkReporter (Phase 4 Step 3)*');

    return lines.join('\n');
  }

  static async writeReports(
    outputDir: string,
    filenamePrefix: string,
    payload: BenchmarkReportPayload
  ): Promise<{ jsonPath: string; mdPath: string }> {
    const jsonPath = path.join(outputDir, `${filenamePrefix}.json`);
    const mdPath = path.join(outputDir, `${filenamePrefix}.md`);

    await fs.mkdir(outputDir, { recursive: true });
    await fs.writeFile(jsonPath, this.generateJsonReport(payload), 'utf-8');
    await fs.writeFile(mdPath, this.generateMarkdownReport(payload), 'utf-8');

    return { jsonPath, mdPath };
  }
}
